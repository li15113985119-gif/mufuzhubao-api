import { chromium } from 'playwright-core';
const browser = await chromium.launch({headless:true, executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const context = await browser.newContext({viewport:{width:390,height:844}});
const page = await context.newPage(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:8080/#/pages/submit/index',{waitUntil:'networkidle'}); await page.waitForTimeout(800);
const inputs=page.locator('input');
await inputs.nth(0).fill('界面验收同学');
await inputs.nth(1).fill('电气自动化 2302');
await inputs.nth(2).fill('qa@example.com');
await page.getByText('请选择软件',{exact:true}).click();
await page.locator('.uni-picker-action-confirm:visible').click();
await page.getByText('请选择故障类型',{exact:true}).click();
await page.locator('.uni-picker-action-confirm:visible').click();
await inputs.nth(3).fill('V17');
await inputs.nth(4).fill('示例提示：界面验收');
const areas=page.locator('textarea');
await areas.nth(0).fill('界面自动化验收：安装环节出现提示。');
await areas.nth(1).fill('界面自动化验收提交的完整问题描述，请在演示数据重置时清除。');
